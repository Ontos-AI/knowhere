from __future__ import annotations

import io
import zipfile

from app.services.document_parser.formats.docx.toc import detect_doc_tocs, detect_sdt_toc
from app.services.document_parser.assets.image_size_filter import is_below_img_min_size
from app.services.document_parser.formats.docx.vml_graphics import (
    is_composite,
    render_composites,
    single_picture_rid,
    vml_pictures,
)
from app.services.document_parser.formats.docx.word_package import (
    normalize_word_package_bytes,
)
from docx import Document
from docx.oxml.table import CT_Tbl
from docx.oxml.text.paragraph import CT_P
from docx.table import Table
from docx.text.paragraph import Paragraph
from loguru import logger
from lxml import etree


def iter_block_items(doc_data):
    doc_data = normalize_word_package_bytes(doc_data)
    doc_stream = io.BytesIO(doc_data)
    doc = Document(doc_stream)

    # python-docx mapping
    p_tbl_map = []
    for child in doc.element.body:
        if isinstance(child, CT_P):
            p_tbl_map.append(("p", child))
        elif isinstance(child, CT_Tbl):
            p_tbl_map.append(("tbl", child))

    with zipfile.ZipFile(io.BytesIO(doc_data), "r") as docx:
        xml = docx.read("word/document.xml")
        rels = etree.fromstring(docx.read("word/_rels/document.xml.rels"))
        rel_map = {
            r.get("Id"): r.get("Target") for r in rels.findall(".//{*}Relationship")
        }
        ns = {
            "a": "http://schemas.openxmlformats.org/drawingml/2006/main",
            "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
            "w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main",
            "v": "urn:schemas-microsoft-com:vml",
            "o": "urn:schemas-microsoft-com:office:office",
            "mc": "http://schemas.openxmlformats.org/markup-compatibility/2006",
        }
        r_ns = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"

        root = etree.fromstring(xml)
        body = root.find(".//w:body", namespaces=ns)
        # Composite VML graphics in the paragraphs read below render together.
        composites = list(
            dict.fromkeys(
                pict
                for paragraph in body.xpath(
                    "w:p | w:sdt/w:sdtContent//w:p", namespaces=ns
                )
                for pict in vml_pictures(paragraph, ns)
                if is_composite(pict, ns)
            )
        )
        composite_images = render_composites(doc_data, root, composites, ns)

        ele_num = 1
        map_index = 0  # point to p_tbl_map
        toc_field_active = False

        for elem in body.iterchildren():
            if not isinstance(elem.tag, str):
                continue

            tag = etree.QName(elem.tag).localname

            # --- SDT (Structured Document Tag) container ---
            # TOC generated by MS Word is usually in sdt
            if tag == "sdt":
                sdt_toc_info = detect_sdt_toc(elem, ns)
                is_toc_sdt = sdt_toc_info["is_toc_sdt"]

                sdt_content = elem.find(".//w:sdtContent", namespaces=ns)
                if sdt_content is not None:
                    for p_elem in sdt_content.findall(".//w:p", namespaces=ns):
                        texts = p_elem.xpath(".//w:t/text()", namespaces=ns)
                        text = "".join(texts).strip()

                        if is_toc_sdt:
                            label = "TOC-AREA"
                            toc_info = detect_doc_tocs(p_elem, ns)
                        else:
                            toc_info = detect_doc_tocs(p_elem, ns)
                            if toc_info["is_style"] or toc_info["is_field_start"]:
                                label = "TOC-AREA"
                            else:
                                label = "PTXT"

                        if text:
                            meta = None
                            if "TOC" in label:
                                meta = {
                                    "toc_level": toc_info.get("toc_level"),
                                    "toc_outline_level": toc_info.get("outline_level"),
                                    "toc_left_indent": toc_info.get("left_indent"),
                                    "toc_style_name": toc_info.get("style_name"),
                                    "toc_source": "sdt",
                                }
                            yield ele_num, text, label, meta
                            ele_num += 1
                        if p_elem.xpath("ancestor::w:p", namespaces=ns):
                            # A text-box paragraph: its images belong to the
                            # enclosing paragraph, which is read as well.
                            continue
                        for content, image_label, image_meta in _paragraph_images(
                            p_elem,
                            text=text,
                            docx=docx,
                            rel_map=rel_map,
                            ns=ns,
                            composite_images=composite_images,
                        ):
                            yield ele_num, content, image_label, image_meta
                            ele_num += 1
                continue

            # --- text paras ---
            if tag == "p":
                texts = elem.xpath(".//w:t/text()", namespaces=ns)
                text = "".join(texts).strip()

                if map_index < len(p_tbl_map) and p_tbl_map[map_index][0] == "p":
                    p_obj = Paragraph(p_tbl_map[map_index][1], doc)
                else:
                    p_obj = None

                toc_info = detect_doc_tocs(elem, ns)
                if toc_info["is_field_start"]:
                    toc_field_active = True

                if toc_info["is_style"] or toc_field_active:
                    label = "TOC-AREA"
                else:
                    label = "PTXT"

                if text or p_obj is not None:
                    meta = None
                    if "TOC" in label:
                        meta = {
                            "toc_level": toc_info.get("toc_level"),
                            "toc_outline_level": toc_info.get("outline_level"),
                            "toc_left_indent": toc_info.get("left_indent"),
                            "toc_style_name": toc_info.get("style_name"),
                            "toc_source": "paragraph",
                        }
                    yield ele_num, p_obj or text, label, meta
                    ele_num += 1

                for content, image_label, image_meta in _paragraph_images(
                    elem,
                    text=text,
                    docx=docx,
                    rel_map=rel_map,
                    ns=ns,
                    composite_images=composite_images,
                ):
                    yield ele_num, content, image_label, image_meta
                    ele_num += 1
                map_index += 1

                if toc_info["is_field_end"]:
                    toc_field_active = False

            # --- tables ---
            elif tag == "tbl":
                if map_index < len(p_tbl_map) and p_tbl_map[map_index][0] == "tbl":
                    tbl = Table(p_tbl_map[map_index][1], doc)
                else:
                    tbl = Table(elem, doc)

                # Extract images from each cell, keyed by (row_idx, col_idx)
                cell_images = {}  # {(row_idx, col_idx): [{'image_name', 'data', 'size'}]}
                for row_idx, tr in enumerate(elem.findall(".//w:tr", namespaces=ns)):
                    for col_idx, tc in enumerate(tr.findall(".//w:tc", namespaces=ns)):
                        cell_seen_rids = set()
                        imgs_in_cell = []
                        # DrawingML images in cell
                        blips = tc.xpath(".//a:blip", namespaces=ns)
                        for b in blips:
                            rid = b.get(f"{r_ns}embed")
                            if not rid or rid in cell_seen_rids:
                                continue
                            target = rel_map.get(rid)
                            if not target or not target.startswith("media/"):
                                continue
                            cell_seen_rids.add(rid)
                            data = docx.read("word/" + target)
                            if is_below_img_min_size(len(data)):
                                continue
                            imgs_in_cell.append(
                                {
                                    "image_name": target.split("/")[-1],
                                    "data": data,
                                    "size": len(data),
                                }
                            )
                        # VML images in cells are skipped, like paragraph VML.
                        if imgs_in_cell:
                            cell_images[(row_idx, col_idx)] = imgs_in_cell

                yield ele_num, tbl, "TABLE", cell_images if cell_images else None
                ele_num += 1
                map_index += 1
            else:
                continue

        # --- handle p_tbl_map at the end ---
        while map_index < len(p_tbl_map):
            tag, node = p_tbl_map[map_index]
            if tag == "p":
                toc_info = detect_doc_tocs(node, ns)
                label = "TOC-AREA" if toc_info["is_style"] else "PTXT"
                meta = None
                if "TOC" in label:
                    meta = {
                        "toc_level": toc_info.get("toc_level"),
                        "toc_outline_level": toc_info.get("outline_level"),
                        "toc_left_indent": toc_info.get("left_indent"),
                        "toc_style_name": toc_info.get("style_name"),
                        "toc_source": "tail-map",
                    }
                yield ele_num, Paragraph(node, doc), label, meta
            elif tag == "tbl":
                yield ele_num, Table(node, doc), "TABLE", None
            ele_num += 1
            map_index += 1


def _paragraph_images(paragraph, *, text, docx, rel_map, ns, composite_images):
    """Images a paragraph holds, or a placeholder for a VML graphic it cannot show."""
    r_ns = f"{{{ns['r']}}}"
    seen_rids = set()
    rendered_composite = False
    # images (DrawingML: <a:blip>)
    for blip in paragraph.xpath(".//a:blip", namespaces=ns):
        image = _media_image(blip.get(f"{r_ns}embed"), docx, rel_map, seen_rids)
        if image is not None:
            yield None, "IMAGE", image

    # Legacy VML: a single picture reads its media file; a composite (<v:group>)
    # comes back as one rendered image, keeping its overlaid text and layout.
    tree = paragraph.getroottree()
    for pict in vml_pictures(paragraph, ns):
        if is_composite(pict, ns):
            rendered = composite_images.get(tree.getpath(pict))
            if rendered is None:
                continue
            image_name, data = rendered
            rendered_composite = True
            yield (
                None,
                "IMAGE",
                {
                    "image_name": image_name,
                    "from": "paragraph",
                    "size": len(data),
                    "data": data,
                },
            )
            continue
        image = _media_image(single_picture_rid(pict, ns), docx, rel_map, seen_rids)
        if image is not None:
            yield None, "IMAGE", image

    # VML that is neither read nor rendered gets a placeholder so the paragraph
    # isn't silently swallowed, leaving its parent section empty.
    if not text and not seen_rids and not rendered_composite:
        vml_groups = paragraph.xpath(".//v:group", namespaces=ns)
        vml_images_check = paragraph.xpath(".//v:imagedata", namespaces=ns)
        if vml_groups or vml_images_check:
            yield "[VML graphic \u2014 extraction not yet supported]", "PTXT", None
            logger.debug(
                f"Injected VML placeholder for paragraph with "
                f"{len(vml_groups)} v:group, {len(vml_images_check)} v:imagedata"
            )


def _media_image(rid, docx, rel_map, seen_rids):
    """The media file a relationship id points at, once per paragraph."""
    if not rid or rid in seen_rids:
        return None
    target = rel_map.get(rid)
    if not target or not target.startswith("media/"):
        return None
    seen_rids.add(rid)
    data = docx.read("word/" + target)
    if is_below_img_min_size(len(data)):
        return None
    return {
        "image_name": target.split("/")[-1],
        "from": "paragraph",
        "size": len(data),
        "data": data,
    }
